MAX_SIZE = 300      #ย่อรูปไม่ให้ด้านยาวเกิน 300 พิกเซลเพื่อให้ประมวลผลเร็ว
NUM_COLORS = 5      #จำนวนสีเด่นที่จะดึงจากแต่ละรูป
SIGNATURE_COLORS = 6  #จำนวนสีในจานสีประจำตัว

